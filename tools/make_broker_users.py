"""Create the Mosquitto password file and access list from .env (Laptop 1 / server only).

Run from the project folder:  python tools/make_broker_users.py
Reads SC_SERVER_USERNAME/PASSWORD and SC_NODE_USERNAME/PASSWORD, writes config/mosquitto/passwd (hashed by
mosquitto_passwd) and config/mosquitto/acl. Re-run after changing a password, then restart Mosquitto.
"""
from __future__ import annotations

import os
import shutil
import stat
import subprocess
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
from smartclass.config import ROOT, credentials  # noqa: E402

CONF = ROOT / "config" / "mosquitto"
ACL = """# Topic access list - generated by tools/make_broker_users.py from .env. Do not edit by hand.

# Laptop 1: Node-RED, ML service, tools - full access to the project's topics.
user {server}
topic readwrite smartclass/#

# Laptop 2: sensor replay + simulated actuators - only what an IoT node needs.
user {node}
topic write smartclass/+/telemetry
topic write smartclass/+/status
topic write smartclass/+/actuator/+
topic write smartclass/+/actuator_status
topic read smartclass/+/control/+
"""


def find_mosquitto_passwd() -> str:
    found = shutil.which("mosquitto_passwd")
    for candidate in [found, r"C:\Program Files\mosquitto\mosquitto_passwd.exe", r"C:\Program Files (x86)\mosquitto\mosquitto_passwd.exe"]:
        if candidate and Path(candidate).exists():
            return candidate
    raise SystemExit("mosquitto_passwd not found. Install Mosquitto (Windows: winget install -e --id EclipseFoundation.Mosquitto; "
                     "Ubuntu: sudo apt install mosquitto mosquitto-clients; macOS: brew install mosquitto).")


def main() -> None:
    server, node = credentials("server"), credentials("node")
    for role, (user, password) in (("SERVER", server), ("NODE", node)):
        if not user or not password:
            raise SystemExit(f"SC_{role}_USERNAME / SC_{role}_PASSWORD missing in .env (copy .env.example to .env first).")
        if password.startswith("change-me"):
            print(f"WARNING: SC_{role}_PASSWORD still has the example value - change it in .env on both laptops.")
    tool = find_mosquitto_passwd()
    passwd = CONF / "passwd"
    CONF.mkdir(parents=True, exist_ok=True)
    passwd.write_text("", encoding="utf-8")
    if os.name != "nt":
        passwd.chmod(stat.S_IRUSR | stat.S_IWUSR)
    for user, password in (server, node):
        subprocess.run([tool, "-b", str(passwd), user, password], check=True)
    (CONF / "acl").write_text(ACL.format(server=server[0], node=node[0]), encoding="utf-8")
    if os.name != "nt" and os.geteuid() == 0 and shutil.which("chown"):
        # Mosquitto started as root drops to the 'mosquitto' user, which must be able to read these files.
        subprocess.run(["chown", "mosquitto", str(passwd), str(CONF / "acl")], check=False)
    print(f"Wrote {passwd} (users: {server[0]}, {node[0]}) and {CONF / 'acl'}")


if __name__ == "__main__":
    main()
